import type { Framework, Language } from "../types/stack.js";
import type { ElementAnalysis, LocatorAnalysis } from "../validation/schema.js";
import type { PageModel } from "./pageModel.js";

export interface GeneratedFile {
  path: string;
  content: string;
  kind: "page" | "component" | "tab" | "config" | "report" | "readme";
}

export interface ProjectSummary {
  pages: number;
  components: number;
  tabs: number;
  elementsAnalyzed: number;
  stable: number;
  avgScore: number;
  fileCount: number;
}

export interface GeneratedProject {
  files: GeneratedFile[];
  summary: ProjectSummary;
}

function indent(code: string, spaces: number): string {
  const pad = " ".repeat(spaces);
  return code
    .split("\n")
    .map((line) => (line.trim() === "" ? line : pad + line))
    .join("\n");
}

function classFor(
  name: string,
  snippets: string[],
  framework: Framework,
  language: Language,
): string {
  const body = snippets.join("\n\n");
  const header = "// Generated by AI Locator Generator";

  if (language === "python") {
    return `${header}\n\nclass ${name}:\n${indent(body, 4)}\n`;
  }
  if (language === "java") {
    const imports =
      framework === "playwright"
        ? "import com.microsoft.playwright.Locator;\nimport com.microsoft.playwright.Page;"
        : "import org.openqa.selenium.By;";
    return `${header}\n\n${imports}\n\npublic class ${name} {\n${indent(body, 4)}\n}\n`;
  }
  if (language === "csharp") {
    return `${header}\n\npublic class ${name}\n{\n${indent(body, 4)}\n}\n`;
  }
  // typescript / javascript
  const imports =
    framework === "playwright"
      ? `import { Page } from "@playwright/test";\n\n`
      : framework === "cypress"
        ? '/// <reference types="cypress" />\n\n'
        : 'import { By } from "selenium-webdriver";\n\n';
  return `${header}\n\n${imports}export class ${name} {\n${indent(body, 2)}\n}\n`;
}

function ownerFolder(type: string, language: Language): string {
  const suffix = language === "java" ? "" : "";
  if (type === "page") return `pages`;
  if (type === "component") return `components`;
  return `tabs`;
}

function sourceRoot(framework: Framework, language: Language): string {
  if (language === "java") return "src/main/java";
  if (language === "python") return "src";
  return "src";
}

function buildConfigFiles(framework: Framework, language: Language): GeneratedFile[] {
  if (language === "java") {
    const dependency =
      framework === "playwright"
        ? `    <dependency>\n      <groupId>com.microsoft.playwright</groupId>\n      <artifactId>playwright</artifactId>\n      <version>1.48.0</version>\n    </dependency>`
        : `    <dependency>\n      <groupId>org.seleniumhq.selenium</groupId>\n      <artifactId>selenium-java</artifactId>\n      <version>4.25.0</version>\n    </dependency>`;
    const pom = `<?xml version="1.0" encoding="UTF-8"?>
<project xmlns="http://maven.apache.org/POM/4.0.0">
  <modelVersion>4.0.0</modelVersion>
  <groupId>com.example</groupId>
  <artifactId>ai-locator-project</artifactId>
  <version>1.0.0</version>
  <properties>
    <maven.compiler.source>17</maven.compiler.source>
    <maven.compiler.target>17</maven.compiler.target>
  </properties>
  <dependencies>
    <dependency>
      <groupId>org.junit.jupiter</groupId>
      <artifactId>junit-jupiter</artifactId>
      <version>5.11.0</version>
      <scope>test</scope>
    </dependency>
${dependency}
  </dependencies>
</project>
`;
    return [{ path: "pom.xml", content: pom, kind: "config" }];
  }
  if (language === "python") {
    const requirements =
      framework === "playwright" ? "playwright\npytest\n" : "selenium\npytest\n";
    return [{ path: "requirements.txt", content: requirements, kind: "config" }];
  }
  // js/ts
  const dep =
    framework === "cypress"
      ? { cypress: "^13.15.0" }
      : framework === "playwright"
        ? { "@playwright/test": "^1.48.0" }
        : { "selenium-webdriver": "^4.25.0" };
  const pkg = JSON.stringify(
    {
      name: "ai-locator-project",
      version: "1.0.0",
      private: true,
      type: "module",
      scripts:
        framework === "cypress" ? { "cy:open": "cypress open" } : { test: 'echo "run your test runner here"' },
      devDependencies: dep,
    },
    null,
    2,
  );
  const files: GeneratedFile[] = [{ path: "package.json", content: pkg + "\n", kind: "config" }];
  if (language === "typescript") {
    files.push({
      path: "tsconfig.json",
      content: JSON.stringify(
        { compilerOptions: { target: "ES2022", module: "NodeNext", moduleResolution: "NodeNext", strict: true, types: framework === "cypress" ? ["cypress"] : [] } },
        null,
        2,
      ) + "\n",
      kind: "config",
    });
  }
  return files;
}

function projectReadme(summary: ProjectSummary, framework: Framework, language: Language, generatedAt: string): string {
  return `# AI Locator Project

Generated by **AI Locator Generator**.

- Framework: ${framework}
- Language: ${language}
- Pages: ${summary.pages}
- Components: ${summary.components}
- Tabs: ${summary.tabs}
- Elements analyzed: ${summary.elementsAnalyzed}
- Stable locators: ${summary.stable}
- Average stability: ${summary.avgScore}/100
- Generated: ${generatedAt}

## Setup

Install dependencies and run your test runner (JUnit, pytest, Playwright Test, or Cypress).
Each class under \`src\` exposes stable element locators for its page, component, or tab.
See \`locator-report.json\` for the full element-level analysis.

## Usage

\`\`\`text
Import the page class, instantiate it with your driver/page/browser context,
and call the exposed locator fields in your tests.
\`\`\`
`;
}

/**
 * Generate the complete automation project from the ownership model:
 * multi-file classes, build configuration, README, and locator report.
 */
export function generateProject(
  pageModel: PageModel,
  elementByElementId: Map<string, ElementAnalysis>,
  analysis: LocatorAnalysis,
  framework: Framework,
  language: Language,
  pageUrl?: string,
): GeneratedProject {
  const files: GeneratedFile[] = [];

  let pages = 0;
  let components = 0;
  let tabs = 0;

  for (const owner of pageModel.owners) {
    const snippets = owner.elements
      .map((el) => elementByElementId.get(el.elementId)?.pageObject.code ?? "")
      .filter((code) => code.trim() !== "");
    if (snippets.length === 0) continue;
    const code = classFor(owner.name, snippets, framework, language);
    const folder = ownerFolder(owner.type, language);
    files.push({
      path: `${sourceRoot(framework, language)}/${folder}/${owner.filename}`,
      content: code,
      kind: owner.type,
    });
    if (owner.type === "page") pages++;
    else if (owner.type === "component") components++;
    else tabs++;
  }

  const report = {
    framework,
    language,
    pageUrl: pageUrl ?? null,
    summary: analysis.summary,
    elements: analysis.elements.map((el) => ({
      elementId: el.elementId,
      element: el.element,
      tag: el.tag,
      primary: el.primary,
      fallbacks: el.fallbacks,
      risks: el.risks,
      validation: el.validation,
      finalScore: el.finalScore ?? el.primary.score,
      pageObject: el.pageObject,
      ownership: ownershipFor(el.elementId, pageModel),
    })),
  };
  files.push({
    path: "locator-report.json",
    content: JSON.stringify(report, null, 2) + "\n",
    kind: "report",
  });

  const summary: ProjectSummary = {
    pages,
    components,
    tabs,
    elementsAnalyzed: analysis.summary.elementsAnalyzed,
    stable: analysis.summary.highConfidence,
    avgScore: analysis.summary.avgScore,
    fileCount: 0,
  };

  files.push({
    path: "README.md",
    content: projectReadme(summary, framework, language, new Date().toISOString()),
    kind: "readme",
  });

  files.push(...buildConfigFiles(framework, language));
  summary.fileCount = files.length;

  return { files, summary };
}

function ownershipFor(
  elementId: string | undefined,
  pageModel: PageModel,
): { type: string; name: string; file: string } | null {
  if (!elementId) return null;
  for (const owner of pageModel.owners) {
    if (owner.elements.some((el) => el.elementId === elementId)) {
      return { type: owner.type, name: owner.name, file: owner.filename };
    }
  }
  return null;
}
