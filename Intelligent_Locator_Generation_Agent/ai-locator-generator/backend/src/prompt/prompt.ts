import type { Framework, Language } from "../types/stack.js";

export interface AnalyzeRequest {
  html?: string;
  pageUrl?: string;
  framework: Framework;
  language: Language;
}

const SYSTEM_PROMPT = `You are a senior QA automation locator engineer. You receive a normalized list of interactive DOM elements extracted from a page, plus the target automation framework and language. Produce locator recommendations as strict JSON.

Scoring model (0-100 per locator):
- Uniqueness 25%: matches exactly one element
- Stability/change resilience 30%: survives re-renders and layout changes
- Readability 15%: clear intent for other engineers
- Specificity 15%: identifies the exact element
- Framework suitability/performance 15%: idiomatic and fast for the selected framework

Strategy preference order (evaluate the actual DOM, never follow blindly):
1. stable data-testid / data-test / data-qa / data-cy attributes
2. accessible role + accessible name
3. stable id
4. stable name
5. stable semantic attributes
6. CSS selector built from stable attributes
7. XPath only when nothing better exists

Hard rules:
- NEVER invent attributes, ids, classes, or text that do not appear in the supplied DOM. Every locator must be derivable from the supplied elements.
- Only emit selectors supported by the selected framework AND language.
- Explain why each primary locator was chosen and note risks (dynamic ids, autogenerated classes, duplicate text, translated labels, layout dependence).
- Use framework-native API style: Playwright -> page.getByRole/getByTestId/locator; Selenium -> By.* in the target language; Cypress -> cy.get/cy.contains.
- Page Object code must be valid, complete, idiomatic code for the selected language: a field declaration plus accessor, e.g. a Playwright/TypeScript getter or Selenium/Java By field.
- Prefer wait-ready patterns (e.g. locator.waitFor in Playwright) over sleeps. Never generate Thread.sleep or hard-coded timeouts.
- Every element in the DOM list MUST appear in the output. Do not skip elements and do not add elements that are not in the list.
- Return ONLY a JSON object, no markdown, no commentary.`;

function frameworkNotes(framework: Framework, language: Language): string {
  const base: Record<Framework, string> = {
    playwright: `Playwright, ${language}. Use page.getByRole('...', { name: '...' }), page.getByTestId('...'), page.locator("...") and page.getByLabel('...').`,
    selenium: `Selenium WebDriver, ${language}. Use framework-native By.* locators (By.id, By.cssSelector, By.xpath, By.name) in the exact ${language} syntax.`,
    cypress: `Cypress, ${language}. Use cy.get("...") with CSS selectors, cy.contains(...), cy.findByRole if testing-library is available.`,
  };
  return base[framework];
}

export function buildSystemPrompt(): string {
  return SYSTEM_PROMPT;
}

export function buildUserPrompt(
  request: AnalyzeRequest,
  elementList: string,
  warnings: string[],
  sourceNote: string,
): string {
  const notes = warnings.length > 0 ? warnings.map((w) => `- ${w}`).join("\n") : "- none";
  const htmlExcerpt = request.html ? request.html.slice(0, 400) : `(fetched from ${request.pageUrl})`;

  return `Target: ${frameworkNotes(request.framework, request.language)}
Source: ${sourceNote}
Original HTML excerpt (for context; use the normalized list as authoritative):
${htmlExcerpt}

Normalized interactive elements (element index is the source order in the DOM):
${elementList}

Extraction warnings:
${notes}

Return strict JSON in exactly this shape:
{
  "summary": { "elementsAnalyzed": <number>, "highConfidence": <number of elements with primary score >= 80>, "avgScore": <0-100>, "warnings": [<strings>] },
  "elements": [
    {
      "element": "<short human label, e.g. 'Login button'>",
      "tag": "<tag name>",
      "primary": { "strategy": "<role|testid|id|name|css|xpath|...>", "locator": "<exact code/selector string>", "score": <0-100>, "reason": "<why chosen>" },
      "fallbacks": [ { "strategy": "<...>", "locator": "<...>", "score": <0-100>, "reason": "<...>" } ],
      "risks": [ "<risk strings, empty array if none>" ],
      "pageObject": { "field": "<camelCase field name>", "code": "<complete code snippet for the selected framework and language>" }
    }
  ]
}`;
}
