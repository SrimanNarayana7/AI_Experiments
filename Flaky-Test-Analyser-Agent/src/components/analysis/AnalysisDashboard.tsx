import type { AnalysisResult, BuildDetails as BuildDetailsType, UploadedBuild } from '../../types/flakyTest';
import { SummaryCards } from './SummaryCards';
import { SuiteHealth } from './SuiteHealth';
import { FlakyTestsTable } from './FlakyTestsTable';
import { ConsistentFailuresTable } from './ConsistentFailuresTable';
import { Recommendations } from './Recommendations';
import { AIAnalysis } from './AIAnalysis';
import { BuildDetails } from './BuildDetails';
import { ErrorState } from '../common/ErrorState';

interface AnalysisDashboardProps {
  result: AnalysisResult;
  build1: UploadedBuild | undefined;
  build2: UploadedBuild | undefined;
  build1Details: BuildDetailsType | undefined;
  build2Details: BuildDetailsType | undefined;
  onNewAnalysis: () => void;
}

export function AnalysisDashboard({
  result,
  build1,
  build2,
  build1Details,
  build2Details,
  onNewAnalysis,
}: AnalysisDashboardProps) {
  const flakyNames = result.flakyTests.map((test) => test.name);
  const failureNames = result.consistentFailures.map((failure) => failure.name);

  return (
    <div className="space-y-6" aria-live="polite">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div>
          <h2 className="text-lg font-semibold text-slate-900">Analysis Results</h2>
          <p className="text-sm text-slate-500">
            Reliability report generated by the FlakyTest AI agent.
          </p>
        </div>
        <button
          type="button"
          onClick={onNewAnalysis}
          className="rounded-md border border-slate-300 bg-white px-3 py-1.5 text-sm font-medium text-slate-700 transition-colors hover:bg-slate-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-slate-400"
        >
          New Analysis
        </button>
      </div>

      {result.fallbackOnly ? (
        <ErrorState
          title="AI analysis received, but structured rendering was unavailable."
          message="The full response is available below in the AI Analysis section."
        />
      ) : null}

      <SummaryCards result={result} />
      <SuiteHealth result={result} />
      <FlakyTestsTable tests={result.flakyTests} />
      <ConsistentFailuresTable failures={result.consistentFailures} />
      <Recommendations
        recommendation={result.rerunRecommendation}
        flakyNames={flakyNames}
        failureNames={failureNames}
      />
      <AIAnalysis rawResponse={result.rawResponse} />
      <BuildDetails
        build1={
          build1 && build1Details
            ? { details: build1Details, content: build1.content }
            : undefined
        }
        build2={
          build2 && build2Details
            ? { details: build2Details, content: build2.content }
            : undefined
        }
      />
    </div>
  );
}
